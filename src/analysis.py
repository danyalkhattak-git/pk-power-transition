"""
Pakistan's power-sector transition, 2000-2025.

Reads the Our World in Data energy dataset (Ember / Energy Institute sources),
produces figures, summary tables and an auto-generated findings file.

Run from repo root:  python src/analysis.py
"""
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "owid-energy-data.csv"
FIG = ROOT / "outputs" / "figures"
TAB = ROOT / "outputs" / "tables"
FIG.mkdir(parents=True, exist_ok=True)
TAB.mkdir(parents=True, exist_ok=True)

COUNTRY = "Pakistan"
PEERS = ["Pakistan", "India", "Bangladesh", "Vietnam", "World"]
START, END = 2000, 2025

SOURCES = {  # OWID column -> label
    "gas_electricity": "Gas",
    "oil_electricity": "Oil",
    "coal_electricity": "Coal",
    "hydro_electricity": "Hydro",
    "nuclear_electricity": "Nuclear",
    "solar_electricity": "Solar",
    "wind_electricity": "Wind",
    "other_renewable_electricity": "Other renewables",
}
COLORS = {
    "Gas": "#8c8c8c", "Oil": "#5b4636", "Coal": "#2f2f2f", "Hydro": "#3b7dd8",
    "Nuclear": "#9b59b6", "Solar": "#f2b705", "Wind": "#5fb3a1",
    "Other renewables": "#9ccc65",
}
PEER_COLORS = {"Pakistan": "#0b6e4f", "India": "#e07a1f", "Bangladesh": "#c0392b",
               "Vietnam": "#3b7dd8", "World": "#7f7f7f"}

plt.rcParams.update({
    "figure.dpi": 150, "axes.spines.top": False, "axes.spines.right": False,
    "axes.titleweight": "normal", "axes.titlesize": 12, "font.size": 10,
})


def load() -> pd.DataFrame:
    df = pd.read_csv(RAW)
    return df[df.year.between(START, END)]


def save(fig, name):
    fig.tight_layout()
    fig.savefig(FIG / f"{name}.png", bbox_inches="tight")
    plt.close(fig)


def fig_mix(pk: pd.DataFrame) -> pd.DataFrame:
    gen = pk[list(SOURCES)].rename(columns=SOURCES).fillna(0)
    share = gen.div(gen.sum(axis=1), axis=0) * 100
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.stackplot(share.index, share.T.values, labels=share.columns,
                 colors=[COLORS[c] for c in share.columns], alpha=0.9)
    ax.set_title("Pakistan electricity generation by source (% of total)")
    ax.set_ylabel("Share of generation (%)")
    ax.set_xlim(START, END)
    ax.set_ylim(0, 100)
    ax.legend(loc="upper left", bbox_to_anchor=(1.01, 1), frameon=False)
    ax.text(0, -0.12, "Source: Our World in Data energy dataset (Ember, Energy Institute).",
            transform=ax.transAxes, fontsize=8, color="#555")
    save(fig, "01_generation_mix")
    gen.round(2).to_csv(TAB / "pakistan_generation_twh.csv")
    share.round(2).to_csv(TAB / "pakistan_generation_share_pct.csv")
    return gen


def fig_peers(df: pd.DataFrame, col: str, title: str, ylabel: str, name: str,
              start: int = 2010):
    sub = df[df.country.isin(PEERS) & (df.year >= start)].pivot(
        index="year", columns="country", values=col)[PEERS]
    fig, ax = plt.subplots(figsize=(8, 4.8))
    for c in PEERS:
        ax.plot(sub.index, sub[c], color=PEER_COLORS[c],
                lw=2.6 if c == COUNTRY else 1.6,
                ls="--" if c == "World" else "-")
        last = sub[c].dropna()
        ax.annotate(c, (last.index[-1], last.iloc[-1]), xytext=(4, 0),
                    textcoords="offset points", va="center",
                    color=PEER_COLORS[c], fontsize=9)
    ax.set_title(title)
    ax.set_ylabel(ylabel)
    ax.set_xlim(start, END + 2)
    ax.set_xticks(range(start, END + 1, 5))
    ax.text(0, -0.12, "Source: Our World in Data energy dataset (Ember, Energy Institute).",
            transform=ax.transAxes, fontsize=8, color="#555")
    save(fig, name)
    sub.round(2).to_csv(TAB / f"{name}.csv")
    return sub


def fig_change(gen: pd.DataFrame, a: int = 2022, b: int = END) -> pd.Series:
    delta = (gen.loc[b] - gen.loc[a]).sort_values()
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.barh(delta.index, delta.values,
            color=["#c0392b" if v < 0 else "#0b6e4f" for v in delta.values])
    ax.axvline(0, color="#333", lw=0.8)
    for i, v in enumerate(delta.values):
        ax.text(v + (0.4 if v >= 0 else -0.4), i, f"{v:+.1f}",
                va="center", ha="left" if v >= 0 else "right", fontsize=9)
    ax.set_title(f"Change in Pakistan electricity generation by source, {a} to {b} (TWh)")
    ax.set_xlabel("TWh")
    save(fig, "05_generation_change")
    delta.round(2).to_csv(TAB / "generation_change_twh.csv", header=["change_twh"])
    return delta


def findings(pk, gen, solar, ci, pc, delta):
    s = pk.set_index("year")
    fossil = ["Gas", "Oil", "Coal"]
    fos_share = gen[fossil].sum(axis=1) / gen.sum(axis=1) * 100
    lines = [
        "# Key findings (auto-generated by src/analysis.py)",
        "",
        f"- Solar's share of Pakistan's electricity rose from {solar.loc[2018, 'Pakistan']:.1f}% (2018) "
        f"to {solar.loc[END, 'Pakistan']:.1f}% ({END}), versus {solar.loc[END, 'India']:.1f}% in India "
        f"and {solar.loc[END, 'World']:.1f}% globally.",
        f"- Solar output grew from {s.loc[2020, 'solar_electricity']:.1f} TWh (2020) to "
        f"{s.loc[END, 'solar_electricity']:.1f} TWh ({END}).",
        f"- Fossil fuels' share of generation fell from {fos_share.loc[2018]:.1f}% (2018) to "
        f"{fos_share.loc[END]:.1f}% ({END}).",
        f"- Carbon intensity of electricity fell from {ci.loc[2017, 'Pakistan']:.0f} gCO2/kWh (2017) to "
        f"{ci.loc[END, 'Pakistan']:.0f} gCO2/kWh ({END}); world: {ci.loc[END, 'World']:.0f}.",
        f"- Per-capita electricity use is {pc.loc[END, 'Pakistan']:.0f} kWh ({END}), about "
        f"{pc.loc[END, 'Pakistan'] / pc.loc[END, 'World'] * 100:.0f}% of the world average and "
        f"{pc.loc[END, 'Pakistan'] / pc.loc[END, 'India'] * 100:.0f}% of India's.",
        f"- Largest change 2022 to {END}: {delta.idxmax()} {delta.max():+.1f} TWh; "
        f"largest fall: {delta.idxmin()} {delta.min():+.1f} TWh.",
        "",
        "Note: latest-year values may be provisional estimates in the source data.",
    ]
    (ROOT / "outputs" / "findings.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def main():
    df = load()
    pk = df[df.country == COUNTRY].set_index("year", drop=False)
    gen = fig_mix(pk)
    solar = fig_peers(df, "solar_share_elec",
                      "Solar share of electricity generation (%)", "%", "02_solar_share_peers")
    ci = fig_peers(df, "carbon_intensity_elec",
                   "Carbon intensity of electricity (gCO2 per kWh)", "gCO2/kWh",
                   "03_carbon_intensity_peers")
    pc = fig_peers(df, "per_capita_electricity",
                   "Electricity generation per person (kWh)", "kWh per person",
                   "04_per_capita_peers")
    delta = fig_change(gen)
    findings(pk.reset_index(drop=True), gen, solar, ci, pc, delta)


if __name__ == "__main__":
    main()
